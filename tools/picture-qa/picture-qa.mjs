#!/usr/bin/env node
// picture-qa — automatic picture gate for procedural film frames. Mandatory: every delivered version of every shot must PASS.
// Pure JS pixel statistics (node:zlib only). It calls no model and needs no ability to "see": the same PNGs give the same JSON
// and PASS/FAIL on any machine, so any model (or a shell script) can run it and act on the result. Spec: tools/picture-qa/README.md.
//
// Input (mixable):
//   node tools/picture-qa/picture-qa.mjs a.png b.png ...      frames of any size (letterbox auto-cropped, analysed at 960 px wide)
//   node tools/picture-qa/picture-qa.mjs --dir DIR             every *.png in DIR (skips *_qa.png, *_diff.png, sheet.png)
//   node tools/picture-qa/picture-qa.mjs --url URL --t 4,12.5  capture via window.__scene.seek/capture first (loopback URL only;
//                                                              --scene ID names the frames <ID>_t<sec>.png; --w/--h resize if supported)
// Per-shot config:
//   --config FILE        per-shot JSON (template: tools/picture-qa/shots.template.json): luma band, warm limit, sky, declared regular
//                        texture areas (allowStripes + why), roi, claim, skip (+ skipWhy). Frame -> shot by file name
//                        <scene>_t<seconds>.png, t<seconds>.png, or frame-<n>.png with --fps / config "fps".
// Compare with the previous version (catches "claimed fixed but the picture did not change"):
//   --compare DIR|a.png,..   previous version frames (same file name, else same order) -> check ⑥ diff + <frame>_diff.png
//   --claim all|stripes,flat,...   checks this version claims to have fixed. Claimed problem regions that changed < --require-change
//                            -> ⑥ FAIL. A claimed check with no detected problem in the previous version needs --roi, else ⑥ FAIL
//                            (unverifiable claim). --claim without --compare is a usage error (exit 2).
//   --roi x0,y0,x1,y1        region claimed fixed (normalised 0..1); it must change too
//   --require-change [F]     changed-pixel fraction threshold (default 0.02); with no claim/roi the whole frame must change >= F
// Other:
//   --luma LO:HI --p99min V --p01max V --drmin V --warm-max V --sky auto|none|F --allow-stripes x0,y0,x1,y1 (override config)
//   --only stripes,halo,flat,luma,clouds,warm,diff    --out DIR (default out/picture-qa/<time>)    --json    --debug
//   --selftest           run the synthetic regression set (tools/picture-qa/samples.json, generated by synth.mjs; no image files)
//   --check-config FILE  validate a per-shot config and exit
// Output: report.json (machine readable: per frame, per check pass/values/regions with box (normalised) and px (source pixels)),
//         report.md, <frame>_qa.png (annotated), <frame>_diff.png (heat map vs previous), sheet.png (contact sheet).
// Exit: 0 all PASS; 1 some FAIL; 2 usage/read/capture/config error; 3 selftest mismatch.
//
// Seven checks (thresholds in TH; see README "Checks"):
//   ① stripes  long straight one-directional stripes (UV/xz projection stretch, striped walls, radial streaks, tile repetition)
//   ② halo     bright outline hugging a dark object (white matte / over-wide rim)
//   ③ flat     large flat-shaded areas without material variation (sky excluded)
//   ④ luma     luminance distribution vs. per-shot band: mean, p01, p99, dynamic range (grey fog / no highlight / no shadow)
//   ⑤ clouds   compact bright cloud blobs in a clear sky (cartoon cumulus)
//   ⑥ diff     difference vs. previous version and whether the claimed problem regions really changed
//   ⑦ warm     warm-pixel fraction ("one point of warmth" budget)
