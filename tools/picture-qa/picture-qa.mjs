// ------------------------------------------------------------------------------------------------ image helpers
export function cropLetterbox(img) {
  const {w, h, R, G, B} = img;
  const isBar = (i0, n, st) => { let dark = 0; for (let k = 0; k < n; k++) { const i = i0 + k * st; if (Math.max(R[i], G[i], B[i]) <= 6 / 255) dark++; } return dark >= n * 0.99; };
  let y0 = 0, y1 = h - 1, x0 = 0, x1 = w - 1;
  while (y0 < h * 0.3 && isBar(y0 * w, w, 1)) y0++;
  while (y1 > h * 0.7 && isBar(y1 * w, w, 1)) y1--;
  while (x0 < w * 0.3 && isBar(y0 * w + x0, y1 - y0 + 1, w)) x0++;
  while (x1 > w * 0.7 && isBar(y0 * w + x1, y1 - y0 + 1, w)) x1--;
  const cw = x1 - x0 + 1, chh = y1 - y0 + 1;
  if (cw === w && chh === h) return {img, crop: [0, 0, w, h]};
  const out = {w: cw, h: chh, R: new Float32Array(cw * chh), G: new Float32Array(cw * chh), B: new Float32Array(cw * chh)};
  for (let y = 0; y < chh; y++) for (let x = 0; x < cw; x++) { const s = (y + y0) * w + x + x0, d = y * cw + x; out.R[d] = R[s]; out.G[d] = G[s]; out.B[d] = B[s]; }
  return {img: out, crop: [x0, y0, cw, chh]};
}
/** Area-weighted separable resample (box filter when shrinking, nearest when enlarging). */
export function resample(img, W2) {
  const {w, h} = img;
  if (w === W2) return img;
  const H2 = Math.max(1, Math.round(h * W2 / w));
  const axis = (n, n2) => {
    const sc = n / n2, taps = [];
    for (let i = 0; i < n2; i++) {
      const a = i * sc, b = (i + 1) * sc, t = [];
      if (sc <= 1) t.push([Math.min(n - 1, Math.floor((a + b) / 2)), 1]);
      else for (let j = Math.floor(a); j < Math.ceil(b); j++) { const wg = Math.min(b, j + 1) - Math.max(a, j); if (wg > 0) t.push([Math.min(n - 1, j), wg / sc]); }
      taps.push(t);
    }
    return taps;
  };
  const tx = axis(w, W2), ty = axis(h, H2);
  const one = (src) => {
    const tmp = new Float32Array(W2 * h), dst = new Float32Array(W2 * H2);
    for (let y = 0; y < h; y++) for (let x = 0; x < W2; x++) { let s = 0; for (const [j, wg] of tx[x]) s += src[y * w + j] * wg; tmp[y * W2 + x] = s; }
    for (let y = 0; y < H2; y++) for (let x = 0; x < W2; x++) { let s = 0; for (const [j, wg] of ty[y]) s += tmp[j * W2 + x] * wg; dst[y * W2 + x] = s; }
    return dst;
  };
  return {w: W2, h: H2, R: one(img.R), G: one(img.G), B: one(img.B)};
}
export function luma(img) { const n = img.w * img.h, Y = new Float32Array(n); for (let i = 0; i < n; i++) Y[i] = 0.2126 * img.R[i] + 0.7152 * img.G[i] + 0.0722 * img.B[i]; return Y; }
export function boxBlur(src, w, h, r) {
  if (r <= 0) return Float32Array.from(src);
  const tmp = new Float32Array(w * h), dst = new Float32Array(w * h);
  for (let y = 0; y < h; y++) { let s = 0; const o = y * w; for (let x = -r; x <= r; x++) s += src[o + Math.min(w - 1, Math.max(0, x))];
    for (let x = 0; x < w; x++) { tmp[o + x] = s / (2 * r + 1); s += src[o + Math.min(w - 1, x + r + 1)] - src[o + Math.max(0, x - r)]; } }
  for (let x = 0; x < w; x++) { let s = 0; for (let y = -r; y <= r; y++) s += tmp[Math.min(h - 1, Math.max(0, y)) * w + x];
    for (let y = 0; y < h; y++) { dst[y * w + x] = s / (2 * r + 1); s += tmp[Math.min(h - 1, y + r + 1) * w + x] - tmp[Math.max(0, y - r) * w + x]; } }
  return dst;
}
function minMax(src, w, h, r, isMax) {
  const tmp = new Float32Array(w * h), dst = new Float32Array(w * h), f = isMax ? Math.max : Math.min;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) { let m = src[y * w + x]; for (let k = Math.max(0, x - r); k <= Math.min(w - 1, x + r); k++) m = f(m, src[y * w + k]); tmp[y * w + x] = m; }
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) { let m = tmp[y * w + x]; for (let k = Math.max(0, y - r); k <= Math.min(h - 1, y + r); k++) m = f(m, tmp[k * w + x]); dst[y * w + x] = m; }
  return dst;
}
/** 8-connected components of a mask -> [{n, x0,y0,x1,y1, idx[]}] */
function components(mask, w, h, keepIdx = false) {
  const lab = new Int32Array(w * h).fill(-1), out = [], st = [];
  for (let i = 0; i < w * h; i++) {
    if (!mask[i] || lab[i] >= 0) continue;
    const c = {n: 0, x0: w, y0: h, x1: -1, y1: -1, idx: keepIdx ? [] : null};
    lab[i] = out.length; st.push(i);
    while (st.length) {
      const j = st.pop(), x = j % w, y = (j / w) | 0;
      c.n++; if (keepIdx) c.idx.push(j);
      if (x < c.x0) c.x0 = x; if (x > c.x1) c.x1 = x; if (y < c.y0) c.y0 = y; if (y > c.y1) c.y1 = y;
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) {
        const xx = x + dx, yy = y + dy; if (xx < 0 || yy < 0 || xx >= w || yy >= h) continue;
        const k = yy * w + xx; if (mask[k] && lab[k] < 0) { lab[k] = out.length; st.push(k); }
      }
    }
    out.push(c);
  }
  return {comps: out, lab};
}
const q = (arr, p) => arr[Math.min(arr.length - 1, Math.max(0, Math.floor(p * (arr.length - 1))))];
const r4 = (x) => Math.round(x * 1e4) / 1e4;
function allowed(opt, x, y) { for (const r of opt.allow || []) if (x >= r[0] && x <= r[2] && y >= r[1] && y <= r[3]) return true; return false; }

// ------------------------------------------------------------------------------------------------ ① stripes / anisotropy
function checkStripes(F, opt) {
  // Directional projection (Radon-like): per 96 px tile, the variance of the 1-D profile averaged along each of 24 directions.
  // A stripe tile = one direction dominates (anisotropy), visible amplitude, at least three periods (zero crossings), and
  // "long and straight": cutting the tile into two halves along the stripe direction, the half-profiles correlate.
  // Natural wind ripples are short and curved (halves uncorrelated); stretched textures, striped walls, perspective-converging
  // streaks and strata bands are long and straight. Isotropic film grain is averaged away along the lines.
  const T = TH.stripes, {w, h, Yb} = F;
  const hp = new Float32Array(w * h); { const lp = boxBlur(Yb, w, h, 12); for (let i = 0; i < w * h; i++) hp[i] = Yb[i] - lp[i]; }
  const cs = T.stride / 2, cw = Math.ceil(w / cs), chh = Math.ceil(h / cs);
  const cell = new Uint8Array(cw * chh), cellAng = new Float32Array(cw * chh), cellAmp = new Float32Array(cw * chh), cellPer = new Float32Array(cw * chh);
  const tiles = [];
  const NA = 24, half = T.tile / 2, nb = Math.ceil(T.tile * 0.75) + 2, NBIN = nb * 2 + 1;
  const pA = new Float64Array(NBIN), cA = new Float64Array(NBIN), p1 = new Float64Array(NBIN), c1 = new Float64Array(NBIN), p2 = new Float64Array(NBIN), c2 = new Float64Array(NBIN);
  const profile = (x0, y0, th, halves) => {
    const c = Math.cos(th), s = Math.sin(th), cx = x0 + half, cy = y0 + half;
    pA.fill(0); cA.fill(0); if (halves) { p1.fill(0); c1.fill(0); p2.fill(0); c2.fill(0); }
    for (let y = y0; y < y0 + T.tile; y++) for (let x = x0; x < x0 + T.tile; x++) {
      const dx = x - cx, dy = y - cy, b = Math.round(dx * c + dy * s) + nb, v = hp[y * w + x];
      pA[b] += v; cA[b]++;
      if (halves) { if (-dx * s + dy * c < 0) { p1[b] += v; c1[b]++; } else { p2[b] += v; c2[b]++; } }
    }
    let cmax = 0; for (let b = 0; b < NBIN; b++) cmax = Math.max(cmax, cA[b]);
    const pv = [], q1 = [], q2 = [];
    for (let b = 0; b < NBIN; b++) if (cA[b] >= cmax * 0.5) {
      pv.push(pA[b] / cA[b]);
      if (halves) { q1.push(c1[b] ? p1[b] / c1[b] : 0); q2.push(c2[b] ? p2[b] / c2[b] : 0); }
    }
    const m = pv.reduce((a, b) => a + b, 0) / pv.length; let v = 0; for (let k = 0; k < pv.length; k++) { pv[k] -= m; v += pv[k] * pv[k]; }
    return {pv, q1, q2, var: v / pv.length};
  };
  for (let ty = 0; ty + T.tile <= h + T.stride / 2; ty += T.stride) for (let tx = 0; tx + T.tile <= w + T.stride / 2; tx += T.stride) {
    const y0 = Math.max(0, Math.min(ty, h - T.tile)), x0 = Math.max(0, Math.min(tx, w - T.tile));
    let m = 0, m2 = 0, n = 0;
    for (let y = y0; y < y0 + T.tile; y++) for (let x = x0; x < x0 + T.tile; x++) { const v = hp[y * w + x]; m += v; m2 += v * v; n++; }
    const tvar = m2 / n - (m / n) ** 2; if (tvar < 1e-8) continue;
    const vs = new Float64Array(NA);
    let bi = 0; for (let a = 0; a < NA; a++) { vs[a] = profile(x0, y0, a * Math.PI / NA, false).var; if (vs[a] > vs[bi]) bi = a; }
    const med = Array.from(vs).sort((p, qq) => p - qq)[NA >> 1];
    const aniso = vs[bi] / (med + 1e-12), amp = Math.sqrt(vs[bi]), ratio = vs[bi] / tvar;
    if (aniso < T.aniso || amp < T.amp) { if (opt.debug) tiles.push({tx: x0, ty: y0, aniso: r4(aniso), amp: r4(amp), ratio: r4(ratio), striped: false}); continue; }
    const P = profile(x0, y0, bi * Math.PI / NA, true), pv = P.pv, L = pv.length;
    const hy = 0.3 * amp; let zc = 0, sg = 0;                       // zero crossings with 0.3 sigma hysteresis
    for (const v of pv) { if (v > hy && sg <= 0) { if (sg < 0) zc++; sg = 1; } else if (v < -hy && sg >= 0) { if (sg > 0) zc++; sg = -1; } }
    const mean = (a) => a.reduce((s, x) => s + x, 0) / a.length;     // correlation of the two halves = "long and straight"
    const m1 = mean(P.q1), m2b = mean(P.q2); let sxy = 0, sxx = 0, syy = 0;
    for (let k = 0; k < L; k++) { const a = P.q1[k] - m1, b = P.q2[k] - m2b; sxy += a * b; sxx += a * a; syy += b * b; }
    const corr = sxy / Math.sqrt(sxx * syy + 1e-18);
    let lagMin = 1, best = -1, bestLag = 0;                            // period (report only)
    const ac = (lag) => { let a = 0; for (let k = 0; k + lag < L; k++) a += pv[k] * pv[k + lag]; return a / ((L - lag) * (P.var + 1e-12)); };
    while (lagMin + 1 < L / 2 && ac(lagMin + 1) <= ac(lagMin)) lagMin++;
    for (let lag = lagMin + 1; lag <= L / 2.5; lag++) { const a = ac(lag); if (a > best) { best = a; bestLag = lag; } }
    const ang = ((bi * 180 / NA + 90) % 180);                           // stripe line direction (0 horizontal, 90 vertical)
    // Near-horizontal bands (±12°): ground perspective compresses any isotropic texture into horizontal bands, so only strong ones count.
    const horiz = ang <= 12 || ang >= 168;
    const striped = zc >= T.zc && corr >= T.corr && ratio >= T.ratio && (!horiz || amp >= T.ampH);
    if (opt.debug) tiles.push({tx: x0, ty: y0, aniso: r4(aniso), amp: r4(amp), ratio: r4(ratio), zc, corr: r4(corr), lag: bestLag, ang, striped});
    if (!striped) continue;
    for (let yy = y0; yy < y0 + T.tile; yy += cs) for (let xx = x0; xx < x0 + T.tile; xx += cs) {
      const k = Math.floor(yy / cs) * cw + Math.floor(xx / cs);
      if (k >= cell.length || allowed(opt, (xx + cs / 2) / w, (yy + cs / 2) / h)) continue;
      cell[k] = 1; cellAng[k] = ang; cellAmp[k] = Math.max(cellAmp[k], amp); cellPer[k] = bestLag || (2 * L / Math.max(zc, 1));
    }
  }
  const {comps} = components(cell, cw, chh, true);
  const total = cw * chh; let marked = 0; for (const v of cell) marked += v;
  const regions = comps.map((cc) => {
    let sa = 0, ca = 0, amp = 0, per = 0;
    for (const k of cc.idx) { const a = cellAng[k] * Math.PI / 90; sa += Math.sin(a); ca += Math.cos(a); amp += cellAmp[k]; per += cellPer[k]; }
    const ang = ((Math.atan2(sa, ca) * 90 / Math.PI) + 180) % 180;
    return {box: [cc.x0 * cs / w, cc.y0 * cs / h, Math.min(1, (cc.x1 + 1) * cs / w), Math.min(1, (cc.y1 + 1) * cs / h)].map(r4), area: r4(cc.n / total), angle: Math.round(ang),
      orient: ang < 20 || ang > 160 ? 'horizontal' : ang > 70 && ang < 110 ? 'vertical' : 'diagonal', amp: r4(amp / cc.n), periodPx: Math.round(per / cc.n)};
  }).sort((a, b) => b.area - a.area);
  const frac = marked / total, largest = regions.length ? regions[0].area : 0;
  let roi = null;
  if (opt.roi) { let rn = 0, rt = 0; for (let y = 0; y < chh; y++) for (let x = 0; x < cw; x++) { const u = (x + 0.5) * cs / w, v = (y + 0.5) * cs / h; if (u >= opt.roi[0] && u <= opt.roi[2] && v >= opt.roi[1] && v <= opt.roi[3]) { rt++; rn += cell[y * cw + x]; } } roi = r4(rn / Math.max(1, rt)); }
  const pass = frac < T.fracFail && largest < T.regionFail && (roi == null || roi < T.roiFail);
  return {pass, frac: r4(frac), largest: r4(largest), roi, regions: regions.slice(0, 8), allowed: opt.allow?.length ? opt.allow.map((rect, i) => ({rect, why: opt.allowWhy?.[i] || ''})) : undefined,
    thresholds: {fracFail: T.fracFail, regionFail: T.regionFail, roiFail: T.roiFail}, _cell: cell, _cw: cw, _cs: cs, ...(opt.debug ? {tiles} : {})};
}

// ------------------------------------------------------------------------------------------------ ② halo (white outline)
function checkHalo(F) {
  const T = TH.halo, {w, h, Yb} = F;
  const open = minMax(minMax(Yb, w, h, T.r, false), w, h, T.r, true);
  const dark = minMax(Yb, w, h, T.darkR, false);
  const mask = new Uint8Array(w * h), TOP = new Float32Array(w * h);
  for (let i = 0; i < w * h; i++) {
    const th = Yb[i] - open[i]; TOP[i] = th;
    if (th > T.th && Yb[i] > T.minY && dark[i] < T.darkK * Yb[i]) mask[i] = 1;
  }
  const {comps} = components(mask, w, h, true);
  const halos = [];
  for (const c of comps) {
    if (c.n < T.minN) continue;
    const bw = c.x1 - c.x0 + 1, bh = c.y1 - c.y0 + 1;
    if (Math.max(bw, bh) < T.minExtent || c.n / (bw * bh) > T.maxFill) continue;
    const bins = [0, 0, 0, 0]; let sth = 0;
    for (const i of c.idx) {
      const y = (i / w) | 0;
      const gx = Yb[Math.min(i + 1, y * w + w - 1)] - Yb[Math.max(i - 1, y * w)], gy = Yb[Math.min(i + w, w * h - 1)] - Yb[Math.max(i - w, 0)];
      const a = ((Math.atan2(gy, gx) * 180 / Math.PI) % 180 + 180) % 180;
      bins[Math.floor(((a + 22.5) % 180) / 45)]++; sth += TOP[i];
    }
    const div = bins.filter((b) => b >= c.n * 0.12).length;          // closed contour = several gradient directions
    if (div < T.minDiv) continue;
    halos.push({box: [c.x0 / w, c.y0 / h, (c.x1 + 1) / w, (c.y1 + 1) / h].map(r4), n: c.n, meanTH: r4(sth / c.n), div, _idx: c.idx});
  }
  halos.sort((a, b) => b.n - a.n);
  const bad = halos.filter((x) => x.n >= T.failN && x.meanTH >= T.failTH);
  return {pass: bad.length === 0, count: halos.length, failing: bad.length, worst: halos.slice(0, 6).map(({_idx, ...r}) => r), thresholds: {failN: T.failN, failTH: T.failTH}, _halos: halos};
}

// ------------------------------------------------------------------------------------------------ block statistics (③ ⑤ sky)
function blockStats(F) {
  const {w, h, Y} = F;
  const dw = Math.floor(w / 4), dh = Math.floor(h / 4), D = new Float32Array(dw * dh);
  for (let y = 0; y < dh; y++) for (let x = 0; x < dw; x++) { let s = 0; for (let j = 0; j < 4; j++) for (let i = 0; i < 4; i++) s += Y[(y * 4 + j) * w + x * 4 + i]; D[y * dw + x] = s / 16; }
  D.set(boxBlur(D, dw, dh, 1));                                        // 3x3 again: film grain drops below the flat threshold
  const cw = Math.floor(dw / 4), chh = Math.floor(dh / 4);
  const mu = new Float32Array(cw * chh), sig = new Float32Array(cw * chh), mx = new Float32Array(cw * chh);
  for (let cy = 0; cy < chh; cy++) for (let cx = 0; cx < cw; cx++) {
    const x0 = Math.max(0, Math.min(dw - 8, cx * 4 - 2)), y0 = Math.max(0, Math.min(dh - 8, cy * 4 - 2));
    let s = 0, sx = 0, sy = 0, s2 = 0, m = 0;
    for (let j = 0; j < 8; j++) for (let i = 0; i < 8; i++) { const v = D[(y0 + j) * dw + x0 + i], xx = i - 3.5, yy = j - 3.5; s += v; sx += v * xx; sy += v * yy; s2 += v * v; m = Math.max(m, v); }
    const a = s / 64, Sxx = 336;                                       // Σ(i−3.5)² over 8×8 = 8·42
    const b = sx / Sxx, c = sy / Sxx;
    const res = Math.max(0, s2 / 64 - a * a - (b * b + c * c) * Sxx / 64);   // plane-fit residual: gradients are not "flat"-penalised
    mu[cy * cw + cx] = a; sig[cy * cw + cx] = Math.sqrt(res); mx[cy * cw + cx] = m;
  }
  return {cw, chh, mu, sig, mx, cellPx: 16};
}
function skyMask(F, BS, mode) {
  const {cw, chh, mu, sig} = BS, sky = new Uint8Array(cw * chh);
  if (mode === 'none') return sky;
  if (mode && typeof mode === 'object' && mode.rects) { for (let y = 0; y < chh; y++) for (let x = 0; x < cw; x++) { const u = (x + 0.5) / cw, v = (y + 0.5) / chh; if (mode.rects.some((r) => u >= r[0] && u <= r[2] && v >= r[1] && v <= r[3])) sky[y * cw + x] = 1; } return sky; }
  if (mode !== 'auto') { const f = +mode; for (let y = 0; y < chh; y++) if ((y + 0.5) / chh < f) for (let x = 0; x < cw; x++) sky[y * cw + x] = 1; return sky; }
  // Horizon: row whose (median over columns) block-mean jump is largest, >= 0.012, and same-signed in >= 50% of columns.
  // No horizon across the frame -> auto mode does not claim any sky (streets, upward pure sky, top-down ground: configure sky).
  let hz = chh;
  { let best = 0;
    for (let r = 2; r < chh - 2; r++) { const ds = []; for (let x = 0; x < cw; x++) ds.push((mu[(r + 1) * cw + x] + mu[Math.min(chh - 1, r + 2) * cw + x]) / 2 - (mu[(r - 1) * cw + x] + mu[(r - 2) * cw + x]) / 2); ds.sort((p, qq) => p - qq); const med = ds[cw >> 1], m = Math.abs(med);
      const cons = ds.filter((d) => Math.sign(d) === Math.sign(med) && Math.abs(d) >= 0.006).length / cw;
      if (cons >= 0.5 && m > best) { best = m; hz = r + 1; } }
    if (best < 0.012) hz = chh; }
  if (hz >= chh) return sky;
  // Above the horizon, flood smooth blocks from the top edge, loosest (sigma, step) level first; components touching the bottom are dropped.
  for (const [tS, tStep] of TH.sky.levels) {
    sky.fill(0);
    const lab = new Uint8Array(cw * chh);
    for (let x0 = 0; x0 < cw; x0++) {
      if (lab[x0] || sig[x0] >= tS) continue;
      const comp = [x0], st = [x0]; lab[x0] = 1; let bottom = false;
      while (st.length) {
        const k = st.pop(), x = k % cw, y = (k / cw) | 0;
        if (y >= chh - 2) bottom = true;
        for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
          const xx = x + dx, yy = y + dy; if (xx < 0 || yy < 0 || xx >= cw || yy >= chh) continue;
          const j = yy * cw + xx; if (yy >= hz || lab[j] || sig[j] >= tS || Math.abs(mu[j] - mu[k]) > tStep) continue;
          lab[j] = 1; st.push(j); comp.push(j);
        }
      }
      if (!bottom) for (const k of comp) sky[k] = 1;
    }
    let n = 0; for (const v of sky) n += v;
    if (n >= cw * chh * 0.03) return sky;
  }
  sky.fill(0);
  return sky;
}
/** Sky zone: all blocks above each column's (windowed lowest) sky edge, so clouds sitting on the horizon are inside it. */
function skyZone(BS, sky) {
  const {cw, chh} = BS, low = new Int32Array(cw).fill(-1), zone = new Uint8Array(cw * chh);
  for (let x = 0; x < cw; x++) for (let y = 0; y < chh; y++) if (sky[y * cw + x]) low[x] = y;
  for (let x = 0; x < cw; x++) {
    let m = -1; for (let k = Math.max(0, x - TH.sky.hwin); k <= Math.min(cw - 1, x + TH.sky.hwin); k++) m = Math.max(m, low[k]);
    if (low[x] < 0 && m >= 0) m = Math.min(m, Math.max(...low.slice(Math.max(0, x - 2), x + 3)));
    for (let y = 0; y <= m; y++) zone[y * cw + x] = 1;
  }
  return zone;
}

// ------------------------------------------------------------------------------------------------ ③ flat
function checkFlat(F, BS, sky, opt) {
  const T = TH.flat, {cw, chh, sig} = BS;
  const flat = new Uint8Array(cw * chh);
  for (let i = 0; i < cw * chh; i++) if (!sky[i] && sig[i] < T.sig) flat[i] = 1;
  const {comps} = components(flat, cw, chh);
  const total = cw * chh; let n = 0; for (const v of flat) n += v;
  const regions = comps.map((c) => ({box: [c.x0 / cw, c.y0 / chh, (c.x1 + 1) / cw, (c.y1 + 1) / chh].map(r4), area: r4(c.n / total)})).sort((a, b) => b.area - a.area);
  const largest = regions.length ? regions[0].area : 0;
  let roi = null;
  if (opt.roi) { let rn = 0, rt = 0; for (let y = 0; y < chh; y++) for (let x = 0; x < cw; x++) { const u = (x + 0.5) / cw, v = (y + 0.5) / chh; if (u >= opt.roi[0] && u <= opt.roi[2] && v >= opt.roi[1] && v <= opt.roi[3]) { rt++; rn += flat[y * cw + x]; } } roi = r4(rn / Math.max(1, rt)); }
  let skyN = 0; for (const v of sky) skyN += v;
  return {pass: largest < T.regionFail && n / total < T.totalFail, total: r4(n / total), largest: r4(largest), skyFrac: r4(skyN / total), regions: regions.slice(0, 6), roi,
    thresholds: {regionFail: T.regionFail, totalFail: T.totalFail, sig: T.sig}, _flat: flat};
}

// ------------------------------------------------------------------------------------------------ ④ luma
function checkLuma(F, opt) {
  const T = {...TH.luma, ...opt.luma};
  const Y = Float32Array.from(F.Y).sort();
  let s = 0; for (const v of Y) s += v; const mean = s / Y.length;
  const st = {mean: r4(mean), p01: r4(q(Y, 0.01)), p05: r4(q(Y, 0.05)), p50: r4(q(Y, 0.5)), p95: r4(q(Y, 0.95)), p99: r4(q(Y, 0.99)), p999: r4(q(Y, 0.999))};
  st.dr = r4(st.p99 - st.p01);
  const fails = [];
  if (mean < T.lo || mean > T.hi) fails.push(`mean ${st.mean} outside [${T.lo},${T.hi}]`);
  if (st.p99 < T.p99min) fails.push(`p99 ${st.p99} < ${T.p99min} (no clear highlight)`);
  if (st.p01 > T.p01max) fails.push(`p01 ${st.p01} > ${T.p01max} (no clear shadow)`);
  if (st.dr < T.drmin) fails.push(`dynamic range ${st.dr} < ${T.drmin} (grey fog over the whole frame)`);
  return {pass: fails.length === 0, ...st, fails, thresholds: T};
}

// ------------------------------------------------------------------------------------------------ ⑤ clouds
function checkClouds(F, BS, sky) {
  const T = TH.clouds, {cw, chh, mu, mx} = BS;
  const zone = skyZone(BS, sky);
  let nz = 0; for (const v of zone) nz += v;
  if (!nz) return {pass: true, skyFrac: 0, blobs: [], cumulus: 0, note: 'no sky detected (configure sky if the frame has one)', _cloud: new Uint8Array(cw * chh), _zone: zone};
  // Mid-scale background = median of sky-zone blocks within ±4 rows / ±6 columns: cumulus is a local bright blob,
  // moon glow and horizon glow are broad and slow and vanish in the difference.
  const RY = T.bgR, RX = T.bgR * 1.5, bg = new Float32Array(cw * chh);
  for (let y = 0; y < chh; y++) for (let x = 0; x < cw; x++) {
    if (!zone[y * cw + x]) continue;
    const vals = [];
    for (let j = Math.max(0, y - RY); j <= Math.min(chh - 1, y + RY); j++) for (let i = Math.max(0, x - RX); i <= Math.min(cw - 1, x + RX); i++) if (zone[j * cw + i]) vals.push(mu[j * cw + i]);
    vals.sort((a, b) => a - b);
    bg[y * cw + x] = vals.length ? vals[Math.floor(vals.length * 0.5)] : mu[y * cw + x];
  }
  const cl = new Uint8Array(cw * chh);
  for (let i = 0; i < cw * chh; i++) if (zone[i] && mu[i] - bg[i] > T.dr) cl[i] = 1;
  const {comps} = components(cl, cw, chh, true);
  const blobs = [];
  for (const c of comps) {
    if (c.n < T.minCells) continue;
    const bw = c.x1 - c.x0 + 1, bh = c.y1 - c.y0 + 1, asp = Math.max(bw / bh, bh / bw);
    let pk = 0, dr = 0, inSky = 0; for (const k of c.idx) { pk = Math.max(pk, mx[k]); dr += mu[k] - bg[k]; inSky += sky[k]; }
    const kind = pk > T.moonY && c.n < 40 ? 'moon/light' : inSky < c.n * 0.4 ? 'edge' : asp > T.maxAspect ? 'cirrus' : 'cumulus';
    blobs.push({box: [c.x0 / cw, c.y0 / chh, (c.x1 + 1) / cw, (c.y1 + 1) / chh].map(r4), cells: c.n, area: r4(c.n / (cw * chh)), contrast: r4(dr / c.n), aspect: r4(asp), kind});
  }
  const bad = blobs.filter((b) => b.kind === 'cumulus');
  return {pass: bad.length === 0, skyFrac: r4(nz / (cw * chh)), blobs: blobs.slice(0, 8), cumulus: bad.length, thresholds: T, _cloud: cl, _zone: zone};
}

// ------------------------------------------------------------------------------------------------ ⑦ warm
function checkWarm(F, opt) {
  const {w, h, R, G, B} = F, max = opt.warmMax ?? TH.warm.max;
  const cs = 16, cw = Math.floor(w / cs), chh = Math.floor(h / cs), cell = new Float32Array(cw * chh);
  let n = 0;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const i = y * w + x, r = R[i], g = G[i], b = B[i], mx = Math.max(r, g, b), mn = Math.min(r, g, b);
    if (mx > TH.warm.minV && r - b > TH.warm.rb && (mx - mn) / mx > TH.warm.sat && r >= g * 0.85) { n++; const cx = Math.min(cw - 1, (x / cs) | 0), cy = Math.min(chh - 1, (y / cs) | 0); cell[cy * cw + cx]++; }
  }
  const m = new Uint8Array(cw * chh); for (let k = 0; k < m.length; k++) m[k] = cell[k] > cs * cs * 0.3 ? 1 : 0;
  const {comps} = components(m, cw, chh);
  const regions = comps.map((c) => ({box: [c.x0 / cw, c.y0 / chh, (c.x1 + 1) / cw, (c.y1 + 1) / chh].map(r4), area: r4(c.n / (cw * chh))})).sort((a, b) => b.area - a.area).slice(0, 6);
  const frac = n / (w * h);
  return {pass: frac <= max, frac: r4(frac), max, regions, thresholds: {max, ...TH.warm}};
}

// ------------------------------------------------------------------------------------------------ ⑥ diff / --compare
function diffMap(F, P) {
  const {w, h} = F, A = boxBlur(F.Y, w, h, 1), B = boxBlur(P.Y, w, h, 1), d = new Float32Array(w * h);
  for (let i = 0; i < w * h; i++) d[i] = Math.abs(A[i] - B[i]);
  return d;
}
function changeIn(d, w, h, box) {
  const x0 = Math.floor(box[0] * w), y0 = Math.floor(box[1] * h), x1 = Math.ceil(box[2] * w), y1 = Math.ceil(box[3] * h);
  let n = 0, c = 0, s = 0;
  for (let y = y0; y < Math.min(h, y1); y++) for (let x = x0; x < Math.min(w, x1); x++) { const v = d[y * w + x]; n++; s += v; if (v > TH.diff.px) c++; }
  return {frac: n ? c / n : 0, mean: n ? s / n : 0};
}
/** Problem regions of every failed check in the previous version. */
function problemBoxes(checks) {
  const out = [], c = checks, add = (check, box) => out.push({check, box});
  if (c.stripes && !c.stripes.pass) for (const g of c.stripes.regions.slice(0, 6)) add('stripes', g.box);
  if (c.halo && !c.halo.pass) for (const g of c.halo.worst.filter((g) => g.n >= TH.halo.failN && g.meanTH >= TH.halo.failTH)) add('halo', g.box);
  if (c.flat && !c.flat.pass) for (const g of c.flat.regions.slice(0, 3)) add('flat', g.box);
  if (c.clouds && !c.clouds.pass) for (const g of c.clouds.blobs.filter((b) => b.kind === 'cumulus')) add('clouds', g.box);
  if (c.warm && !c.warm.pass) for (const g of c.warm.regions.slice(0, 3)) add('warm', g.box);
  if (c.luma && !c.luma.pass) add('luma', [0, 0, 1, 1]);
  return out;
}
function compare(F, P, R, opt) {
  if (P.w !== F.w || P.h !== F.h) return {pass: false, error: `size mismatch ${P.w}x${P.h} vs ${F.w}x${F.h}`};
  const prevChecks = cleanR(core(P, {...opt, only: (opt.only || CHECKS).filter((k) => k !== 'diff')}));
  const d = diffMap(F, P), full = changeIn(d, F.w, F.h, [0, 0, 1, 1]);
  const req = opt.requireChange ?? TH.diff.require;
  const probs = problemBoxes(prevChecks);
  const claim = opt.claim === 'all' ? 'all' : (opt.claim || []);
  if (opt.roi) probs.push({check: 'roi', box: opt.roi});
  const cur = cleanR(R);
  for (const p of probs) {
    const c = changeIn(d, F.w, F.h, p.box);
    p.changedFrac = r4(c.frac); p.meanAbs = r4(c.mean);
    p.nowPass = p.check === 'roi' ? null : (cur[p.check] ? cur[p.check].pass : null);
    p.verdict = c.frac < req || c.mean < TH.diff.meanMin ? 'unchanged' : p.nowPass === false ? 'changed_still_fail' : 'fixed';
    p.claimed = p.check === 'roi' || claim === 'all' || claim.includes(p.check);   // unclaimed old problems are listed as open, not failed
  }
  const bad = probs.filter((p) => p.claimed && p.verdict === 'unchanged');
  // A named claim with nothing detected in the previous version and no roi cannot be verified -> FAIL (point at it with --roi).
  const unverified = claim === 'all' ? [] : claim.filter((k) => k !== 'diff' && !probs.some((p) => p.check === k) && !opt.roi);
  const anyClaim = probs.some((p) => p.claimed);
  const pass = bad.length === 0 && unverified.length === 0 && (anyClaim || !opt.requireChangeExplicit || full.frac >= req);
  const summary = (probs.length ? `${probs.filter((p) => p.verdict !== 'unchanged').length}/${probs.length} previous problem regions changed (claimed ${probs.filter((p) => p.claimed).length})` : 'previous version had no failed check')
    + (bad.length ? `; ${bad.length} claimed fixed but unchanged` : '') + (unverified.length ? `; unverifiable claim (${unverified.join(',')}): previous version shows no detected problem, give --roi` : '')
    + (!anyClaim && opt.requireChangeExplicit && full.frac < req ? `; whole frame changed ${r4(full.frac)} < ${req}` : '');
  return {pass, mode: 'compare', requireChange: req, changedFracFull: r4(full.frac), meanAbsFull: r4(full.mean), prevFailed: [...new Set(probs.filter((p) => p.check !== 'roi').map((p) => p.check))],
    claim: opt.claim || [], unverifiedClaims: unverified, problems: probs, summary, _d: d};
}

