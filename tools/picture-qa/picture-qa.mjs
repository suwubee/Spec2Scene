export function writeReport(outDir, results, meta) {
  const allPass = results.every((r) => r.pass);
  fs.writeFileSync(path.join(outDir, 'report.json'), JSON.stringify({tool: 'picture-qa', version: 1, ...meta, pass: allPass, thresholds: TH, results}, null, 1));
  const L = ['# picture-qa report', '', `frames: ${results.length}   verdict: **${allPass ? 'PASS' : 'FAIL'}**   config: ${meta.config || '(none)'}`, '',
    '| frame | shot | ① stripes | ② halo | ③ flat | ④ luma | ⑤ clouds | ⑦ warm | ⑥ vs previous | verdict |', '|---|---|---|---|---|---|---|---|---|---|'];
  const cell = (c, s) => (!c ? '—' : `${c.pass === false ? '**FAIL**' : 'PASS'} ${s}`);
  for (const r of results) {
    const c = r.checks;
    L.push(`| ${r.name || path.basename(r.file || '')} | ${r.shot || ''} | ${cell(c.stripes, c.stripes ? `${(c.stripes.frac * 100).toFixed(1)}%` : '')} | ${cell(c.halo, c.halo ? `${c.halo.failing}/${c.halo.count}` : '')} | ${cell(c.flat, c.flat ? `${(c.flat.largest * 100).toFixed(1)}%` : '')} | ${cell(c.luma, c.luma ? `mean ${(c.luma.mean * 100).toFixed(1)}% p99 ${(c.luma.p99 * 100).toFixed(0)}%` : '')} | ${cell(c.clouds, c.clouds ? `${c.clouds.cumulus ?? 0}` : '')} | ${cell(c.warm, c.warm ? `${(c.warm.frac * 100).toFixed(1)}%` : '')} | ${cell(c.diff, c.diff ? (c.diff.summary || c.diff.error || '') : '')} | ${r.pass ? 'PASS' : '**FAIL**'} |`);
  }
  L.push('', 'Legend `<frame>_qa.png`: red = ① stripe tiles, yellow = ② halo pixels, cyan = ③ flat blocks, magenta = ⑤ cloud blocks, green line = sky lower edge, orange box = ⑦ warm area, green/red box = ⑥ previous problem region (red = unchanged). `<frame>_diff.png` = |ΔY| ×8 vs previous. JSON `box` is normalised 0..1 on the analysed frame, `px` is source pixels.');
  for (const r of results) {
    const fails = [], c = r.checks, px = (g) => `px[${(g.px || []).join(',')}]`;
    if (c.stripes && !c.stripes.pass) fails.push(`① stripes ${(c.stripes.frac * 100).toFixed(1)}% (largest ${(c.stripes.largest * 100).toFixed(1)}%): ` + c.stripes.regions.slice(0, 3).map((g) => `${g.orient} ${g.angle}° period ${g.periodPx}px ${px(g)}`).join('; '));
    if (c.halo && !c.halo.pass) fails.push('② halo: ' + c.halo.worst.slice(0, 3).map((g) => `n=${g.n} strength ${g.meanTH} ${px(g)}`).join('; '));
    if (c.flat && !c.flat.pass) fails.push(`③ flat largest ${(c.flat.largest * 100).toFixed(1)}% / total ${(c.flat.total * 100).toFixed(1)}% ${px(c.flat.regions[0] || {})}`);
    if (c.luma && !c.luma.pass) fails.push('④ luma: ' + c.luma.fails.join('; '));
    if (c.clouds && !c.clouds.pass) fails.push('⑤ clouds: ' + c.clouds.blobs.filter((b) => b.kind === 'cumulus').map((b) => `${b.cells} blocks contrast ${b.contrast} ${px(b)}`).join('; '));
    if (c.warm && !c.warm.pass) fails.push(`⑦ warm ${(c.warm.frac * 100).toFixed(1)}% > ${(c.warm.max * 100).toFixed(1)}%: ` + c.warm.regions.slice(0, 3).map(px).join('; '));
    if (c.diff && !c.diff.pass) fails.push(`⑥ vs previous: ${c.diff.summary || c.diff.error}: ` + (c.diff.problems || []).filter((p) => p.verdict === 'unchanged' && p.claimed).map((p) => `${p.check} ${px(p)} changed ${(p.changedFrac * 100).toFixed(1)}%`).join('; '));
    if (fails.length) L.push('', `### ${r.name || path.basename(r.file || '')}`, ...fails.map((f) => '- ' + f));
  }
  fs.writeFileSync(path.join(outDir, 'report.md'), L.join('\n') + '\n');
  const sheetRows = results.map((r) => r._sheet).filter(Boolean);
  if (sheetRows.length) writeSheet(sheetRows, path.join(outDir, 'sheet.png'));
}
function prevFor(file, prev, idx) {
  if (!prev) return null;
  const p = String(prev);
  if (fs.existsSync(p) && fs.statSync(p).isDirectory()) { const f = path.join(p, path.basename(file)); if (fs.existsSync(f)) return f; const all = fs.readdirSync(p).filter((x) => x.endsWith('.png') && !/_qa\.png$|_diff\.png$|^sheet\.png$/.test(x)).sort(); return all[idx] ? path.join(p, all[idx]) : null; }
  return p.split(',')[idx] || null;
}

// ------------------------------------------------------------------------------------------------ selftest (synthetic only)
export async function runSelftest({out = null, samplesFile = path.join(HERE, 'samples.json'), log = console.log} = {}) {
  const {renderScene} = await import('./synth.mjs');
  const spec = JSON.parse(fs.readFileSync(samplesFile, 'utf8'));
  if (out) fs.mkdirSync(out, {recursive: true});
  const rows = [], results = [], cache = new Map();
  let bad = 0;
  const resolve = (ref) => {
    if (typeof ref === 'string') { if (!ref.startsWith('@') || !spec.scenes?.[ref.slice(1)]) throw new Error(`unknown scene reference ${ref}`); return resolve(spec.scenes[ref.slice(1)]); }
    if (ref && ref.base) { const {base, addLayers = [], ...rest} = ref, b = resolve(base); return {...b, ...rest, layers: [...(b.layers || []), ...addLayers]}; }
    return ref;
  };
  const render = (ref) => { const scene = resolve(ref), k = JSON.stringify(scene); if (!cache.has(k)) cache.set(k, renderScene(scene)); return cache.get(k); };
  for (const s of spec.samples) {
    const cfg = s.config ? validateConfig(s.config, `sample ${s.id}`) : {};
    const opt = shotOpts(s.frame || `${s.id}.png`, cfg, {only: s.only || null, claim: s.claim || null, roi: s.roi || null, warmMax: s.warmMax ?? null, sky: s.sky ?? null, luma: s.luma || {}, requireChange: s.requireChange ?? null});
    const r = analyzeImage(render(s.scene), opt, s.prev ? render(s.prev) : null);
    r.name = s.id;
    if (out) { const base = s.id.replace(/[^a-z0-9_.-]/gi, '_'); fs.writeFileSync(path.join(out, base + '.png'), imageToPNG(render(s.scene))); writeFrameOutputs(r, out, base); }
    results.push(r);
    for (const [k, want] of Object.entries(s.expect)) {
      const got = r.checks[k] ? (r.checks[k].pass ? 'PASS' : 'FAIL') : 'n/a', ok = got === want;
      if (!ok) bad++;
      rows.push({ok, id: s.id, check: k, want, got, note: s.note || ''});
    }
  }
  if (out) writeReport(out, results, {selftest: true, samples: path.basename(samplesFile)});
  for (const r of rows) log(`${r.ok ? 'ok  ' : 'MISS'}  ${r.id.padEnd(28)} ${r.check.padEnd(8)} want ${r.want} got ${r.got}   ${r.note}`);
  log(bad ? `\nselftest: ${bad} expectation(s) not met` : `\nselftest: all ${rows.length} expectations met (${spec.samples.length} synthetic frames, no image files)`);
  const covered = {}; for (const r of rows) (covered[r.check] ??= new Set()).add(r.want);
  return {bad, rows, results, covered: Object.fromEntries(Object.entries(covered).map(([k, v]) => [k, [...v].sort()]))};
}

// ------------------------------------------------------------------------------------------------ CLI
function parseArgs(argv) {
  const a = {_: [], allow: []};
  for (let i = 0; i < argv.length; i++) {
    const s = argv[i];
    if (!s.startsWith('--')) { a._.push(s); continue; }
    const k = s.slice(2), nx = argv[i + 1];
    const flag = ['selftest', 'json', 'debug', 'help'].includes(k) || nx === undefined || nx.startsWith('--');
    const v = flag ? true : argv[++i];
    if (k === 'allow-stripes') a.allow.push(String(v).split(',').map(Number)); else a[k] = v;
  }
  if (a.prev && !a.compare) a.compare = a.prev;
  return a;
}
async function capture(a, outDir) {
  const url = new URL(String(a.url));
  if (!['127.0.0.1', 'localhost', '[::1]'].includes(url.hostname)) throw new Error('--url must be a loopback address');
  const {browser, prepare, auditPage, sceneReady} = await import('../lib/browser.mjs');
  const session = await browser(), files = [];
  try {
    const page = await session.newPage({viewport: {width: +(a.w || 960), height: +(a.h || 540)}, deviceScaleFactor: 1});
    const check = auditPage(page);
    await prepare(page, url.href); await sceneReady(page);
    if (a.w && a.h) await page.evaluate(async ([w, h]) => { if (typeof window.__scene.resize === 'function') await window.__scene.resize(w, h); }, [+a.w, +a.h]);
    for (const t of String(a.t).split(',').map(Number)) {
      if (!Number.isFinite(t)) throw new Error('--t must be comma separated seconds');
      const dataUrl = await page.evaluate(async (tt) => { await window.__scene.seek(tt); return window.__scene.capture(); }, t);
      const f = path.join(outDir, `${a.scene ? a.scene + '_' : ''}t${t.toFixed(3).padStart(7, '0')}.png`);
      fs.writeFileSync(f, Buffer.from(String(dataUrl).split(',')[1], 'base64')); files.push(f);
    }
    check();
  } finally { await session.close(); }
  return files;
}
async function main() {
  const a = parseArgs(process.argv.slice(2));
  if (a.help || (!a._.length && !a.dir && !a.url && !a.selftest && !a['check-config'])) {
    console.log(fs.readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').filter((l) => l.startsWith('//')).map((l) => l.slice(3)).join('\n'));
    return a.help ? 0 : 2;
  }
  if (a['check-config']) { loadConfig(a['check-config']); console.log(`config OK: ${a['check-config']}`); return 0; }
  if (a.selftest) { const r = await runSelftest({out: a.out ? path.resolve(a.out) : null}); return r.bad ? 3 : 0; }
  if (a.claim && !a.compare) throw new Error('--claim requires --compare <previous version frames>: a fix claim must be verified against the previous picture');
  const outDir = path.resolve(a.out || path.join('out', 'picture-qa', new Date().toISOString().replace(/[:.]/g, '-')));
  fs.mkdirSync(outDir, {recursive: true});
  const files = a._.slice();
  if (a.dir) files.push(...fs.readdirSync(a.dir).filter((f) => f.endsWith('.png') && !/_qa\.png$|_diff\.png$|^sheet\.png$/.test(f)).sort().map((f) => path.join(a.dir, f)));
  if (a.url) { if (!a.t) throw new Error('--url requires --t'); const fd = path.join(outDir, 'frames'); fs.mkdirSync(fd, {recursive: true}); files.push(...await capture(a, fd)); }
  if (!files.length) throw new Error('no frames');
  const {file: cfgFile, cfg} = loadConfig(a.config);
  const cli = {scene: a.scene || null, fps: a.fps ? +a.fps : null, only: a.only ? String(a.only).split(',') : null, debug: !!a.debug, allow: a.allow,
    luma: {}, warmMax: a['warm-max'] != null ? +a['warm-max'] : null, sky: a.sky ? (isNaN(+a.sky) ? a.sky : +a.sky) : null,
    roi: a.roi ? String(a.roi).split(',').map(Number) : null,
    claim: a.claim ? (a.claim === 'all' ? 'all' : String(a.claim).split(',')) : null,
    requireChange: a['require-change'] == null ? null : (a['require-change'] === true ? TH.diff.require : +a['require-change'])};
  if (cli.claim && cli.claim !== 'all' && !cli.claim.every((c) => CHECKS.includes(c))) throw new Error(`--claim must be "all" or a subset of ${CHECKS.join(',')}`);
  if (cli.roi && !isRect(cli.roi)) throw new Error('--roi must be normalised x0,y0,x1,y1');
  if (a.luma) { const [lo, hi] = String(a.luma).split(':').map(Number); Object.assign(cli.luma, {lo, hi}); }
  for (const k of ['p99min', 'p01max', 'drmin']) if (a[k] != null) cli.luma[k] = +a[k];
  const results = files.map((f, i) => {
    const opt = shotOpts(f, cfg, cli);
    if (!a.compare) delete opt.claim;                                   // config claims only apply when comparing
    const prev = prevFor(f, a.compare, i);
    if (a.compare && !prev) throw new Error(`no previous frame for ${f}`);
    return analyzeFile(f, opt, prev, outDir);
  });
  writeReport(outDir, results, {args: process.argv.slice(2), config: cfgFile});
  const pass = results.every((r) => r.pass);
  if (a.json) console.log(JSON.stringify(results, null, 1));
  else {
    for (const r of results) console.log(`${r.pass ? 'PASS' : 'FAIL'}  ${path.basename(r.file)}  ${r.shot || ''}  ` + Object.entries(r.checks).map(([k, v]) => `${k}:${v.pass === false ? 'FAIL' : 'ok'}`).join(' '));
    console.log(`report: ${path.join(outDir, 'report.md')}  json: ${path.join(outDir, 'report.json')}  sheet: ${path.join(outDir, 'sheet.png')}`);
  }
  return pass ? 0 : 1;
}
